#!/usr/bin/env python3
"""Generate the work SSH fragment from the infra_management Ansible inventory.

The inventory contains internal hostnames, addresses and usernames, so it is
deliberately NOT committed to nixconf (which is a public repository). This
script reads the checkout that already lives on the work machines and writes a
private fragment to ~/.ssh/config.d/work. Home-manager includes that directory
from modules/system/ssh.nix; the activation hook refreshes it on every switch.

Sources, in order:
  1. <infra_management>/inventories/prod/inventory.yml  (all hosts with ansible_host)
  2. ~/.config/nixconf/work-ssh-extra.conf               (optional raw Host blocks)

Usage:
  sync-work-ssh                     # refresh ~/.ssh/config.d/work
  sync-work-ssh --check             # exit 1 if the fragment is stale
  sync-work-ssh --print             # write the fragment to stdout

Environment:
  NIXCONF_WORK_INVENTORY   override the inventory path
"""

from __future__ import annotations

import argparse
import configparser
import os
import sys
from pathlib import Path

import yaml

DEFAULT_RELATIVE_INVENTORY = "repos/work/infra_management/inventories/prod/inventory.yml"
DEFAULT_EXTRA = "~/.config/nixconf/work-ssh-extra.conf"
DEFAULT_OUTPUT = "~/.ssh/config.d/work"


def default_inventory() -> Path:
    override = os.environ.get("NIXCONF_WORK_INVENTORY")
    if override:
        return Path(override).expanduser()
    return Path.home() / DEFAULT_RELATIVE_INVENTORY


def read_default_user(ansible_cfg: Path) -> str | None:
    if not ansible_cfg.is_file():
        return None
    parser = configparser.ConfigParser(interpolation=None)
    try:
        parser.read(ansible_cfg)
        return parser.get("defaults", "remote_user", fallback=None)
    except configparser.Error:
        return None


def collect_hosts(inventory: Path, default_user: str | None) -> dict[str, dict[str, str]]:
    data = yaml.safe_load(inventory.read_text())
    if not isinstance(data, dict):
        raise ValueError("inventory root is not a mapping")

    hosts: dict[str, dict[str, str]] = {}

    def walk(node: object, inherited: dict[str, str]) -> None:
        if not isinstance(node, dict):
            return

        variables = dict(inherited)
        group_vars = node.get("vars")
        if isinstance(group_vars, dict):
            variables.update({str(k): str(v) for k, v in group_vars.items()})

        entries = node.get("hosts")
        if isinstance(entries, dict):
            for name, host_vars in entries.items():
                host_vars = host_vars if isinstance(host_vars, dict) else {}
                user = (
                    host_vars.get("ansible_user") or variables.get("ansible_user") or default_user
                )
                host_name = host_vars.get("ansible_host") or name
                port = host_vars.get("ansible_port") or variables.get("ansible_port")
                entry = {
                    "host": str(name),
                    "hostName": str(host_name),
                }
                if user:
                    entry["user"] = str(user)
                if port:
                    entry["port"] = str(port)
                hosts[entry["host"]] = entry

        children = node.get("children")
        if isinstance(children, dict):
            for child in children.values():
                walk(child, variables)

    for group in data.values():
        walk(group, {})

    return hosts


def render(hosts: dict[str, dict[str, str]], extra: Path) -> str:
    lines = [
        "# Generated by sync-work-ssh. Do not edit this file directly.",
        f"# Inventory-derived hosts: {len(hosts)}",
        "# Local additions: " + str(extra),
        "",
    ]

    for name in sorted(hosts, key=str.casefold):
        entry = hosts[name]
        lines.append(f"Host {entry['host']}")
        lines.append(f"  HostName {entry['hostName']}")
        if entry.get("user"):
            lines.append(f"  User {entry['user']}")
        if entry.get("port") and entry["port"] != "22":
            lines.append(f"  Port {entry['port']}")
        lines.append("")

    if extra.is_file():
        lines.append("# --- local additions (work-ssh-extra.conf) ---")
        lines.append(extra.read_text().rstrip())
        lines.append("")

    return "\n".join(lines)


def write_private(path: Path, content: str) -> None:
    path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_text(content)
    temporary.chmod(0o600)
    temporary.replace(path)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--inventory", type=Path, default=default_inventory())
    parser.add_argument("--extra", type=Path, default=Path(DEFAULT_EXTRA).expanduser())
    parser.add_argument("--output", type=Path, default=Path(DEFAULT_OUTPUT).expanduser())
    parser.add_argument("--ansible-config", type=Path, default=None)
    parser.add_argument("--check", action="store_true", help="exit 1 when the fragment is stale")
    parser.add_argument(
        "--print", dest="print_only", action="store_true", help="print instead of writing"
    )
    parser.add_argument("--quiet", action="store_true", help="suppress informational output")
    args = parser.parse_args()

    inventory = args.inventory.expanduser()
    if not inventory.is_file():
        print(
            f"sync-work-ssh: inventory not found at {inventory}; leaving "
            f"{args.output.expanduser()} untouched",
            file=sys.stderr,
        )
        return 0

    ansible_cfg = args.ansible_config
    if ansible_cfg is None:
        ansible_cfg = inventory.parents[2] / "ansible.cfg"
    default_user = read_default_user(ansible_cfg.expanduser())

    try:
        hosts = collect_hosts(inventory, default_user)
    except (OSError, ValueError, yaml.YAMLError) as error:
        print(f"sync-work-ssh: cannot parse {inventory}: {error}", file=sys.stderr)
        return 1

    content = render(hosts, args.extra.expanduser())

    if args.print_only:
        sys.stdout.write(content)
        return 0

    output = args.output.expanduser()
    current = output.read_text() if output.is_file() else None
    if args.check:
        if current != content:
            print(f"sync-work-ssh: {output} is out of date", file=sys.stderr)
            return 1
        if not args.quiet:
            print(f"sync-work-ssh: {output} is up to date")
        return 0

    if current == content:
        if not args.quiet:
            print(f"sync-work-ssh: {output} already up to date ({len(hosts)} hosts)")
        return 0

    write_private(output, content)
    if not args.quiet:
        print(f"sync-work-ssh: wrote {len(hosts)} hosts to {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
